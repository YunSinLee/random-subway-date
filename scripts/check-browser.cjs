async function openDrawSettings(page) {
  if (await page.locator('#draw-settings').isVisible()) return
  await page.locator('#course-open-settings:visible, #open-settings:visible').click()
}

async function closeDrawSettings(page) {
  await page.locator('#close-settings').click()
}

async function openCourseSettings(page) {
  const settings = page.locator('#course-settings')
  if (await settings.getAttribute('open') === null) await settings.locator('summary').click()
}

async function chooseNextCandidate(page, key, label) {
  const picker = page.locator(`#course [data-category="${key}"] .candidate-picker`)
  const options = picker.locator('li button')
  const before = await options.allTextContents()
  const selected = await options.evaluateAll((nodes) => nodes.findIndex((node) => node.getAttribute('aria-pressed') === 'true'))
  await page.getByRole('button', { name: label + ' 바꾸기', exact: true }).click()
  assert.ok(await picker.getAttribute('open') !== null)
  assert.equal(await options.evaluateAll((nodes) => nodes.findIndex((node) => node.getAttribute('aria-pressed') === 'true')), selected)
  await options.nth((selected + 1) % before.length).click()
}

